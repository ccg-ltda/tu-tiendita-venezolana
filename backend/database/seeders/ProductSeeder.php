use RuntimeException;

class ProductSeeder extends Seeder
{
    public function run(): void
    {
        $categoryIds = Category::query()->pluck('id', 'slug');

        foreach ($this->products() as $data) {
            $categoryId = $categoryIds->get($data['category_slug']);

            if ($categoryId === null) {
                throw new RuntimeException("Missing category [{$data['category_slug']}] while seeding products.");
            }

            $subcategoryId = Subcategory::query()
                ->where('category_id', $categoryId)
                ->where('slug', $data['subcategory_slug'])
                ->value('id');

            if ($subcategoryId === null) {
                throw new RuntimeException("Missing subcategory [{$data['subcategory_slug']}] while seeding products.");
            }

            Product::query()->updateOrCreate(
                [
                    'category_id' => $categoryId,
                    'subcategory_id' => $subcategoryId,
                    'name' => $data['name'],
                    'presentation' => $data['presentation'],
                ],
                [
                    'category' => $data['category'],
                    'subcategory' => $data['subcategory'],
                    'price_cop' => $data['price_cop'],
                    'inventory' => $data['inventory'],
                    'active' => $data['active'],
                    'image_path' => $data['image_path'],
                    'legacy_img' => $data['legacy_img'],
                    'revision' => $data['revision'],
                ],
            );
        }
    }

